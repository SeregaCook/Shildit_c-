import cowsay

# 1. Приветствие и имя
print("=== ТЕКСТОВЫЙ КВЕСТ: ПОБЕГ ИЗ ПЕЩЕРЫ ===")
player_name = input("Введи имя своего героя: ")

cowsay.dragon(f"Гр-р-р! Я дракон Смог! Приветствую тебя, {player_name}!")

# 2. Выбор оружия
print("\nПеред тобой лежит три предмета:")
print("1 - Волшебная палочка")
print("2 - Меч")
print("3 - Жареная курица")

weapon = input("Что выберешь? Напиши цифру (1, 2 или 3): ")

# 3. Проверка условий
if weapon == "1":
    # daemon вместо ghost
    cowsay.daemon("Ты кастуешь заклинание! Дракон превратился в тираннозавра и убежал!")
elif weapon == "2":
    # dragon вместо trex
    cowsay.dragon("Твой меч сломался о чешую! Дракон зарычал и съел тебя!")
elif weapon == "3":
    # meow вместо kitty
    cowsay.meow("Дракон оказался просто голодным! Он съел курицу и стал мурчать, как котик.")
else:
    cowsay.cow("Ты долго думал, и мимо проходила корова...")

print("\n--- КОНЕЦ ИГРЫ ---")