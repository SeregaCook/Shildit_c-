import time

# Регистры процессора Марсохода
registers = {"A": 0, "B": 0, "C": 0}
flag_equal = False

def print_cpu(step_name):
    print(f"\n--- [ {step_name} ] ---")
    print(f"📦 Регистр A: {registers['A']} | 📦 Регистр B: {registers['B']} | 📦 Регистр C: {registers['C']}")
    print(f"🚩 Зеленый флаг (Equal): {flag_equal}")
    time.sleep(0.5)

def MOV(reg, val):
    registers[reg] = val if isinstance(val, int) else registers[val]
    print_cpu(f"MOV {reg}, {val}")

def ADD(reg1, reg2_or_val):
    val = reg2_or_val if isinstance(reg2_or_val, int) else registers[reg2_or_val]
    registers[reg1] += val
    print_cpu(f"ADD {reg1}, {val}")

def SUB(reg1, reg2_or_val):
    val = reg2_or_val if isinstance(reg2_or_val, int) else registers[reg2_or_val]
    registers[reg1] -= val
    print_cpu(f"SUB {reg1}, {val}")

def CMP(reg1, reg2_or_val):
    global flag_equal
    val = reg2_or_val if isinstance(reg2_or_val, int) else registers[reg2_or_val]
    flag_equal = (registers[reg1] == val)
    print_cpu(f"CMP {reg1}, {val}")

# ==========================================
# 🚀 КОД ДЕТЕЙ ПИШЕТСЯ НИЖЕ:
# ==========================================

# Уровень 1: Зарядка батарей (A = 100, B = 50)
MOV("A", 100)
MOV("B", 50)

# Уровень 2: Перекачка энергии из A в C
SUB("A", 30)
ADD("C", "A")

# Уровень 3: Сканер Марсианского Золота
MOV("A", 15)
CMP("A", 15)

# Уровень 4: Сбор 5 кристаллов в цикле
MOV("A", 0)
MOV("B", 5)

while not flag_equal:
    ADD("A", 1)
    ADD("C", 10)
    CMP("A", "B")

print("\n🎉 Миссия выполнена! Марсоход готов к работе!")

